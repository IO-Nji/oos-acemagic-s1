#!/usr/bin/env python3
"""Bake Orbitron glyphs into src/core/font_orbitron.cpp.

Usage: tools/bake_fonts.py /path/to/Orbitron/static

Needs Pillow. Run it only when a font size or weight changes; the generated file is
committed so that building the panel needs neither Python nor the TTF files.
Glyphs are 4-bit alpha, two pixels per byte, each glyph padded to a whole byte.
"""
import sys
from pathlib import Path
from PIL import ImageFont

# role, weight, pixel size
FONTS = [
    ("Small", "SemiBold", 10),
    ("Title", "Bold", 10),
    ("Large", "Bold", 18),
]
FIRST, LAST = 0x20, 0x7E


def bake(ttf: Path, size: int):
    font = ImageFont.truetype(str(ttf), size)
    cap_top = font.getbbox("H")[1]
    cap_height = font.getbbox("H")[3] - cap_top
    digit_advance = max(round(font.getlength(d)) for d in "0123456789")
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        bbox = font.getbbox(ch)
        mask = font.getmask(ch)
        w, h = mask.size
        xoff, yoff = bbox[0], bbox[1] - cap_top
        offset = len(data)
        nibbles = [mask.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
        if len(nibbles) % 2:
            nibbles.append(0)
        for i in range(0, len(nibbles), 2):
            data.append((nibbles[i] << 4) | nibbles[i + 1])
        glyphs.append((offset, w, h, xoff, yoff, advance, ch))
    return cap_height, digit_advance, glyphs, data


def main():
    src = Path(sys.argv[1])
    out = Path(__file__).resolve().parent.parent / "src" / "core" / "font_orbitron.cpp"
    lines = [
        "// Generated by tools/bake_fonts.py - do not edit.",
        "// Glyphs derived from Orbitron (SIL Open Font License 1.1, see third_party/Orbitron-OFL.txt).",
        '#include "core/font_data.hpp"',
        "",
    ]
    for role, weight, size in FONTS:
        cap, digit, glyphs, data = bake(src / f"Orbitron-{weight}.ttf", size)
        name = f"orbitron{role}"
        lines.append(f"// Orbitron {weight} {size}px, cap height {cap}px")
        lines.append(f"static const uint8_t {name}Alpha[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const Glyph {name}Glyphs[] = {{")
        for offset, w, h, xoff, yoff, advance, ch in glyphs:
            label = ch if ch not in "\\/*" else f"0x{ord(ch):02X}"
            lines.append(f"    {{{offset}, {w}, {h}, {xoff}, {yoff}, {advance}}},  // {label}")
        lines.append("};")
        lines.append(
            f"const FontData FONT_{role.upper()} = {{{name}Glyphs, {name}Alpha, "
            f"{FIRST}, {LAST - FIRST + 1}, {cap}, {digit}}};"
        )
        lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
